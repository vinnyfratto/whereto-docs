// Builds the Solar icon block in custom.css from the app's own icon set.
//   node docs/operations/zoho-helpcenter/build-icons.js
//
// Zoho draws its portal icons from an SVG sprite (<use href="#search">), and we
// can only reach them with CSS. So each icon becomes a mask: the Solar SVG is
// the mask, background-color is the ink. The duotone half-opacity layer
// survives as half-alpha in the mask, so the icons stay two-tone in one color.
//
// Glyphs come from src/components/icons/generated.ts first (the app's bundle,
// which carries our custom plane and globe), then straight from Solar.

const fs = require('fs');
const path = require('path');
const { getIconData, iconToSVG, iconToHTML, replaceIDs } = require('@iconify/utils');
const solar = require('@iconify-json/solar/icons.json');

const ROOT = path.resolve(__dirname, '../../..');
const CSS = path.join(__dirname, 'custom.css');
const START = '/* ICONS:START (generated by build-icons.js, do not edit by hand) */';
const END = '/* ICONS:END */';

const bundle = {};
const gen = fs.readFileSync(path.join(ROOT, 'src/components/icons/generated.ts'), 'utf8');
for (const m of gen.matchAll(/^\s+(\w+): `(<svg[^`]*)`,?$/gm)) bundle[m[1]] = m[2];

function svgFor(name) {
  if (bundle[name]) return bundle[name];
  const data = getIconData(solar, name + '-bold-duotone');
  if (!data) throw new Error(`No icon "${name}" in the app bundle or Solar bold-duotone`);
  const built = iconToSVG(data, { height: '24', width: '24' });
  return iconToHTML(replaceIDs(built.body), built.attributes);
}

function maskUrl(name) {
  // Masks only read alpha, so paint everything black.
  const svg = svgFor(name).replace(/currentColor/g, '#000');
  // Light escaping (quotes swapped, only <>#% encoded) keeps the CSS small.
  const data = svg.replace(/"/g, "'").replace(/[<>#%]/g, encodeURIComponent);
  return `url("data:image/svg+xml,${data}")`;
}

// Zoho sprite id -> [icon, ink]. Ink is a CSS color; `currentColor` keeps
// whatever Zoho already colors that spot (white inside the azure search button).
const SPRITES = {
  search:                 ['magnifer', 'currentColor'],
  formSearch:             ['magnifer', 'var(--wt-text-muted)'],
  Capa2:                  ['notebook-bookmark', 'var(--wt-azure)'],   // home: Knowledge Base card
  Capa3:                  ['ticket', 'var(--wt-azure)'],              // home: Tickets card
  briefCase:              ['documents', 'var(--wt-azure)'],           // list headings
  relatedArticle:         ['documents', 'var(--wt-azure)'],
  document:               ['document-text', 'var(--wt-azure)'],       // article rows
  tickCircle:             ['check-circle', 'var(--wt-azure)'],
  threedot:               ['menu-dots', 'var(--wt-text-muted)'],
  downArrow:              ['alt-arrow-down', 'var(--wt-text-muted)'],
  pdfDownload:            ['download-minimalistic', 'var(--wt-text-muted)'],
  print:                  ['printer', 'var(--wt-text-muted)'],
  readerViewRight:        ['maximize-square', 'var(--wt-text-muted)'],
  like:                   ['like', 'var(--wt-text-muted)'],           // Zoho flips it for dislike
  attachment:             ['paperclip', 'var(--wt-text-muted)'],
  refresh:                ['refresh', 'var(--wt-text-muted)'],
  arrowRightThick:        ['arrow-right', '#fff'],                   // back to top; Zoho rotates it
  accessibility_settings: ['accessibility', 'var(--wt-text)'],
};

// Knowledge Base category tiles are uploaded images, matched by the category
// name Zoho puts in the alt text. Renaming a category in Desk needs a new key.
const CATEGORIES = {
  'Flights':               'planeIcon_custom',
  'Hotels':                'bed',
  'Payments & Refunds':    'card',
  'WhereTo Account & App': 'smartphone',
  'Getting Help':          'question-circle',
};

const out = [START];
for (const [id, [icon, ink]] of Object.entries(SPRITES)) {
  const sel = `svg:has(> use[*|href="#${id}"])`;
  out.push(
    `${sel} { --wt-i: ${maskUrl(icon)}; background-color: ${ink} !important; -webkit-mask: var(--wt-i) center / contain no-repeat; mask: var(--wt-i) center / contain no-repeat; }`,
    `${sel} > use { display: none; }`,
  );
}
for (const [alt, icon] of Object.entries(CATEGORIES)) {
  const sel = `.Avatar__avatar:has(> img[alt="${alt}"])`;
  out.push(
    `${sel} { --wt-i: ${maskUrl(icon)}; background-color: var(--wt-azure) !important; -webkit-mask: var(--wt-i) center / 80% no-repeat; mask: var(--wt-i) center / 80% no-repeat; }`,
    `${sel} > img { opacity: 0; }`,
  );
}
out.push(END);

let css = fs.readFileSync(CSS, 'utf8');
const block = out.join('\n');
css = css.includes(START)
  ? css.slice(0, css.indexOf(START)) + block + css.slice(css.indexOf(END) + END.length)
  : css.replace(/\n*$/, '\n\n/* Icons: Solar bold-duotone, same set as the app */\n' + block + '\n');
fs.writeFileSync(CSS, css);
console.log(`custom.css: ${Object.keys(SPRITES).length} sprite icons, ${Object.keys(CATEGORIES).length} category icons`);
